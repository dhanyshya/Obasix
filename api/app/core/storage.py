"""Private file storage for quote attachments and design proofs: a port of src/lib/storage/files.ts.

With BLOB_READ_WRITE_TOKEN set, files go to the same private Vercel Blob store the site uses,
speaking the protocol of @vercel/blob 2.x (api version 13); a test replays the official SDK's
requests against this client. Otherwise files live in OBASIX_FILES_DIR on this server, which
must be the site's `.data` directory when both run on one machine.

Keys are always generated by our code (e.g. "proof-files/PRF-1234.png"), never taken from a request.
"""

import secrets
import time
from pathlib import Path
from urllib.parse import quote

import httpx

from app.core.config import get_settings

API_VERSION = "13"
DEFAULT_API_URL = "https://vercel.com/api/blob"


class StorageError(RuntimeError):
    pass


def _token() -> str:
    return get_settings().blob_token


def blob_configured() -> bool:
    return bool(_token())


def _store_id(token: str) -> str:
    # vercel_blob_rw_<storeId>_<secret>, as the SDK reads it.
    parts = token.split("_")
    return parts[3] if len(parts) > 3 else ""


def _local_path(key: str) -> Path:
    root = Path(get_settings().files_dir).resolve()
    # Every part reduced to its basename, so a key can never leave the folder.
    parts = [Path(part).name for part in key.split("/") if Path(part).name not in ("", ".", "..")]
    return root.joinpath(*parts)


async def save_file(key: str, data: bytes, content_type: str) -> None:
    if not blob_configured():
        path = _local_path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return
    token = _token()
    store_id = _store_id(token)
    api_url = get_settings().blob_api_url or DEFAULT_API_URL
    headers = {
        "x-api-blob-request-id": f"{store_id}:{int(time.time() * 1000)}:{secrets.token_hex(7)}",
        "x-vercel-blob-store-id": store_id,
        "x-api-blob-request-attempt": "0",
        "x-api-version": API_VERSION,
        "authorization": f"Bearer {token}",
        "x-vercel-blob-access": "private",
        "x-content-type": content_type,
        "x-add-random-suffix": "0",
        "x-allow-overwrite": "1",
    }
    async with httpx.AsyncClient(timeout=30) as client:
        for attempt in range(3):
            headers["x-api-blob-request-attempt"] = str(attempt)
            try:
                response = await client.put(f"{api_url}/?pathname={quote(key, safe='')}", content=data, headers=headers)
            except httpx.HTTPError as error:
                if attempt == 2:
                    raise StorageError(f"Blob upload failed: {error}") from error
                continue
            if response.is_success:
                return
            if response.status_code < 500 or attempt == 2:
                raise StorageError(f"Blob upload failed: {response.status_code}")


def blob_read_url(key: str) -> str:
    override = get_settings().blob_read_url  # tests only
    if override:
        return f"{override.rstrip('/')}/{key}"
    return f"https://{_store_id(_token())}.private.blob.vercel-storage.com/{key}"


async def load_file(key: str) -> bytes | None:
    if not blob_configured():
        path = _local_path(key)
        return path.read_bytes() if path.is_file() else None
    async with httpx.AsyncClient(timeout=30) as client:
        try:
            response = await client.get(blob_read_url(key), headers={"authorization": f"Bearer {_token()}"})
        except httpx.HTTPError:
            return None
    return response.content if response.status_code == 200 else None


def sniff_type(data: bytes) -> str | None:
    """Content signature → type (src/lib/files.ts)."""
    if data[:4] == b"\x89PNG":
        return "image/png"
    if data[:3] == b"\xff\xd8\xff":
        return "image/jpeg"
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "image/webp"
    if data[:4] == b"%PDF":
        return "application/pdf"
    return None


EXTENSIONS = {"image/png": "png", "image/jpeg": "jpg", "image/webp": "webp", "application/pdf": "pdf"}
