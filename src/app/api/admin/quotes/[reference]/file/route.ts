import { readFile } from "node:fs/promises";
import path from "node:path";
import { readAdminSession } from "@/lib/admin/auth";
import { findDemoQuote } from "@/lib/quotes/demo-store";

export const runtime = "nodejs";

const notFound = () => new Response("Not found", { status: 404 });

/** The customer's quote attachment, for staff only. */
export async function GET(_request: Request, context: { params: Promise<{ reference: string }> }) {
  if (!(await readAdminSession())) return notFound();
  const { reference } = await context.params;
  const quote = await findDemoQuote(reference.slice(0, 40));
  const stored = quote?.attachment?.storedAs;
  if (!quote || !stored) return notFound();
  // storedAs was generated by the quote route; basename() keeps it inside the folder regardless.
  const bytes = await readFile(path.join(process.cwd(), ".data", "quote-files", path.basename(stored))).catch(() => null);
  if (!bytes) return notFound();
  return new Response(new Uint8Array(bytes), {
    headers: {
      "content-type": quote.attachment!.type,
      "content-disposition": `attachment; filename="${path.basename(stored)}"`,
      "cache-control": "private, no-store",
      "x-content-type-options": "nosniff",
    },
  });
}
