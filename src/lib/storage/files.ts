import "server-only";

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { get, put } from "@vercel/blob";

/**
 * Private file storage for quote attachments and design proofs.
 * With BLOB_READ_WRITE_TOKEN set, files go to a private Vercel Blob store
 * (works on serverless hosting); otherwise they stay in .data/ on this server.
 * Files are never public: routes stream them only after checking who's asking.
 */
export function blobConfigured() {
  return Boolean(process.env.BLOB_READ_WRITE_TOKEN);
}

const localPath = (key: string) => path.join(process.cwd(), ".data", ...key.split("/").map((part) => path.basename(part)));

/** Saves a file under a key such as "proof-files/PRF-1234.png". Keys are generated by our code, never taken from a request. */
export async function saveFile(key: string, bytes: Uint8Array, contentType: string) {
  if (blobConfigured()) {
    await put(key, Buffer.from(bytes), { access: "private", contentType, addRandomSuffix: false, allowOverwrite: true });
    return;
  }
  const file = localPath(key);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, bytes);
}

export async function loadFile(key: string): Promise<Uint8Array | null> {
  if (blobConfigured()) {
    const result = await get(key, { access: "private" }).catch(() => null);
    if (!result || result.statusCode !== 200) return null;
    return new Uint8Array(await new Response(result.stream).arrayBuffer());
  }
  return readFile(localPath(key))
    .then((b) => new Uint8Array(b))
    .catch(() => null);
}
